// Ejercicio 1: Terreno rectangular
// Declaramos constantes para base y altura
const base = 20; 
const altura = 10;

// Variables para área y perímetro
let area = base * altura;
let perimetro = 2 * (base + altura);

// Mostramos resultados
console.log("Área del terreno:", area);
console.log("Perímetro del terreno:", perimetro);

// Ejercicio 2: Promedio de notas
const nota1 = 4.5;
const nota2 = 3.8;
const nota3 = 2.9;

let promedio = (nota1 + nota2 + nota3) / 3;

console.log("Promedio del estudiante:", promedio);

